#!/usr/bin/env node
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const root = new URL(".", import.meta.url).pathname;
const rows = Array.from({ length: 12 }, (_, index) => {
  const band = index < 3 ? "shortcut" : index < 8 ? "playbook" : "judgment";
  const tool = index % 3 === 0 ? "save-execution-summary" : "run-subagent";
  return {
    task_id: `synthetic-${String(index + 1).padStart(2, "0")}`,
    band,
    request: { messages: [{ role: "user", content: `Synthetic ${band} routing case ${index + 1}.` }] },
    label: { calls: [{ tool, arguments: tool === "run-subagent" ? { subagentPath: "ops/triage" } : {} }] },
  };
});

const split = (name, selected) => {
  const bytes = selected.map((row) => JSON.stringify(row)).join("\n") + "\n";
  writeFileSync(join(root, `${name}.jsonl`), bytes);
  return createHash("sha256").update(bytes).digest("hex");
};

mkdirSync(dirname(join(root, "smoke.jsonl")), { recursive: true });
writeFileSync(join(root, "smoke.jsonl"), rows.map((row) => JSON.stringify(row)).join("\n") + "\n");
const hashes = {
  tasks: createHash("sha256").update(rows.map((row) => JSON.stringify(row)).join("\n") + "\n").digest("hex"),
  train: split("train", rows.slice(0, 6)),
  dev: split("dev", rows.slice(6, 9)),
  holdout: split("holdout", rows.slice(9)),
};
writeFileSync(join(root, "FREEZE.md"), `# Synthetic smoke freeze\n\nGenerated by ` + "`generate-smoke.mjs`" + `.\n\n- tasks: \`${hashes.tasks}\`\n- train: \`${hashes.train}\`\n- dev: \`${hashes.dev}\`\n- holdout: \`${hashes.holdout}\` (clean; never executed)\n- rows: 12 total, split 6 / 3 / 3\n`);
